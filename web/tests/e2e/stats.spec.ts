import { test, expect } from '@playwright/test'

test('record list shows every record once, grouped, with primary sources', async ({ page }) => {
  await page.goto('/stats')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('champion ever')
  await page.getByText('See all 229 records', { exact: true }).click()
  const list = page.locator('details').filter({ hasText: 'See all 229 records' })
  await expect(list.locator('li')).toHaveCount(229)
  await expect(list.getByRole('region')).toHaveCount(4)
  await expect(list.getByRole('region', { name: 'All-time F1 records: 72' })).toContainText('Youngest world champion')
  await expect(list.getByRole('link', { name: /Guinness World Records/ }).first()).toHaveAttribute('href', /guinnessworldrecords/)
  await expect(list.getByRole('link')).toHaveCount(11)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('stats navigation and light theme remain usable', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('f1-theme', 'light'))
  await page.goto('/stats')
  const menu = page.getByRole('button', { name: 'Toggle menu' })
  if (await menu.isVisible()) await menu.click()
  await expect(page.getByRole('link', { name: 'STATS', exact: true })).toBeVisible()
  if (await menu.isVisible()) await menu.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('stats charts replay the title race and inspect races, seasons and champions', async ({ page }) => {
  await page.goto('/stats')
  await expect(page.getByText('Mexico City GP · 1 Nov 2026')).toBeVisible()
  const titleChart = page.getByRole('img', { name: /Championship points after round/ })
  await expect(titleChart).toHaveAttribute('aria-label', /round 19.*Antonelli 380/)
  const slider = page.getByRole('slider', { name: 'Championship round' })
  await slider.focus()
  await slider.press('Home')
  await expect(titleChart).toHaveAttribute('aria-label', /round 1, Australian.*Russell 25/)
  await page.getByRole('button', { name: 'Play season replay' }).click()
  await expect(titleChart).toHaveAttribute('aria-label', /round [2-9]/, { timeout: 5000 })
  await page.getByRole('button', { name: 'Pause season replay' }).click()

  const card = page.locator('#race-by-race article')
  await expect(card).toContainText('ITALIAN GP', { ignoreCase: true })
  await expect(card).toContainText('+18 places on Sunday')
  await page.getByRole('button', { name: 'Round 6, Monaco: P1' }).click()
  await expect(card).toContainText('Monte Carlo')
  await page.locator('#race-by-race').getByRole('button', { name: /^2025/ }).click()
  await expect(page.getByRole('group', { name: '2025 form guide' }).getByRole('button')).toHaveCount(24)

  await expect(page.getByRole('img', { name: /Qualifying 2026: Antonelli ahead 11 times, Russell ahead 8 times/ })).toBeAttached()
  await page.getByRole('button', { name: /Sebastian Vettel/ }).click()
  await expect(page.locator('#youngest')).toContainText('3 years, 66 days')
  await expect(page.getByText('20 years, 68 days')).toHaveCount(0)
  const context = page.locator('#title-context')
  await expect(context.getByRole('listitem').filter({ hasText: 'Last: Ascari 1953' })).toContainText('73')
  await expect(context.locator('li[data-kimi="true"]')).toContainText('Antonelli')
  await expect(context.getByRole('list', { name: 'Title firsts' }).getByRole('listitem')).toHaveCount(4)
  await expect(context.getByRole('link')).toHaveCount(4)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
})

test('record charts link weekends, milestone ladders and comparison groups', async ({ page }) => {
  await page.goto('/stats')
  const weekend = page.locator('article').filter({ hasText: 'Grand Prix weekend' })
  await expect(weekend).toContainText('Chinese Grand Prix weekend', { ignoreCase: true })
  await expect(weekend.locator('li')).toHaveCount(15)
  await page.getByRole('group', { name: 'Busiest weekends' }).getByRole('button', { name: /Monaco ’26/ }).click()
  await expect(weekend).toContainText('Youngest grand slam')
  await page.getByRole('group', { name: /Records per race weekend/ }).press('ArrowRight')
  await expect(weekend).not.toContainText('Monaco Grand Prix', { ignoreCase: true })

  await page.getByRole('group', { name: 'Milestone' }).getByRole('button', { name: /^Podiums/ }).click()
  await expect(page.getByRole('img', { name: /Career podiums: 19\. Youngest ever to 9 through 19 podiums/ })).toBeAttached()
  await expect(page.getByText('Youngest driver ever to reach 19 podiums.')).toBeVisible()

  await expect(page.getByText(/72 of 229/)).toBeVisible()
  await page.getByRole('button', { name: /Team and nation/ }).click()
  await expect(page.locator('[data-focus="team"]')).toBeAttached()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
