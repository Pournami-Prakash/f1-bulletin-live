import { test, expect } from '@playwright/test'

test('record periods, sources and trivia work without horizontal overflow', async ({ page }) => {
  await page.goto('/stats')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('REWRITING')
  await expect(page.getByRole('status')).toContainText('8 selected records')
  await expect(page.getByRole('heading', { name: 'Youngest Sprint polesitter', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Whole career', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('12 selected records')
  await expect(page.getByRole('heading', { name: 'Youngest Sprint polesitter', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Before 2026', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('4 selected records')
  await expect(page.getByRole('heading', { name: 'Youngest Formula 1 World Champion', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '2026 season', exact: true }).click()
  await expect(page.getByRole('button', { name: '2026 season', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('link', { name: /Source for Youngest Grand Prix polesitter/ })).toHaveAttribute('href', /guinnessworldrecords/)
  await page.getByText('Is Kimi the youngest Grand Prix winner, too?', { exact: false }).click()
  await expect(page.getByText('Max Verstappen retains that record.', { exact: false })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `/tmp/stats-${test.info().project.name}.png`, fullPage: true })
})

test('stats is reachable in the site navigation and supports the light theme', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('f1-theme', 'light'))
  await page.goto('/stats')
  const menu = page.getByRole('button', { name: 'Toggle menu' })
  if (await menu.isVisible()) await menu.click()
  await expect(page.getByRole('link', { name: 'STATS', exact: true })).toBeVisible()
  if (await menu.isVisible()) await menu.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: `/tmp/stats-light-${test.info().project.name}.png`, fullPage: true })
})
